"""Generates src/kernels/v9_dispatch_table.inc from the tuning runs (robust selection).

Every results/tune_sgemm_*.csv (or the files given with --csv) is a separate tuning run. For each
(config, size) the score is the MEAN % of paired cuBLAS over the runs that measured it. A config
is eligible only if it passed the cuBLAS check in every run and size it appeared in, and (when at
least two runs exist) only if it was measured in at least two runs: a single noisy run can't win.
For each size the eligible config with the best mean is chosen. v9_autotuned.cu #includes the
table and uses the entry closest (log scale) to cbrt(M*N*K).

Picking the best of many configs still biases the winner upward a little, so bench measures v9 /
v12 again in their own run; only that measurement is reported.

Usage: .venv/Scripts/python scripts/gen_dispatch.py [--csv f1.csv f2.csv ...] [--min-runs N]
"""
import argparse
from pathlib import Path

import pandas as pd

from results_io import RESULTS, ROOT

OUT = ROOT / "src" / "kernels" / "v9_dispatch_table.inc"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--csv", type=Path, nargs="*")
    ap.add_argument("--min-runs", type=int, default=None)
    args = ap.parse_args()
    paths = args.csv or sorted(RESULTS.glob("tune_sgemm_*.csv"))
    if not paths:
        raise SystemExit("no results/tune_sgemm_*.csv")
    frames = []
    for i, p in enumerate(paths):
        d = pd.read_csv(p)
        d = d[d.kernel != "cublas"].assign(run=i)
        frames.append(d)
    t = pd.concat(frames)
    failed = set(t[t.status != "PASS"].kernel)
    ok = t[~t.kernel.isin(failed)]
    g = ok.groupby(["kernel", "M"]).pct_cublas.agg(["mean", "count", "min", "max"]).reset_index()
    min_runs = args.min_runs if args.min_runs is not None else (2 if len(paths) >= 2 else 1)
    g = g[g["count"] >= min_runs]
    lines = [f"// GENERATED by scripts/gen_dispatch.py from {len(paths)} tuning run(s): "
             + ", ".join(f"results/{Path(p).name}" for p in paths) + ".",
             "// Do not edit: rerun the script after new tuning runs.",
             f"// {{size, config}}: best MEAN % of paired cuBLAS at that size over the runs"
             f" (configs measured in >= {min_runs} run(s), passing everywhere)."]
    for n in sorted(g.M.unique()):
        h = g[g.M == n]
        b = h.loc[h["mean"].idxmax()]
        lines.append(f'{{{int(n)}, "{b.kernel}"}},  // mean {b["mean"]:.1f}% over {int(b["count"])} run(s), '
                     f'range {b["min"]:.1f}-{b["max"]:.1f}%')
    if failed:
        lines.append("// excluded (failed the cuBLAS check somewhere): " + ", ".join(sorted(failed)))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
