"""Generates src/kernels/v9_dispatch_table.inc from the newest tuning run.

For every size in results/tune_sgemm_*.csv it picks the configuration with the highest % of
paired cuBLAS, among configurations that passed the cuBLAS check at EVERY size (a config that
failed anywhere is never dispatched). v9_autotuned.cu #includes the table; at run time it uses
the entry whose size is closest (in log scale) to cbrt(M*N*K).

The winning numbers in the tuning run are biased upward (best of many noisy measurements), so
bench measures v9 again, independently; only that measurement is reported for v9.

Usage: .venv/Scripts/python scripts/gen_dispatch.py [--csv results/tune_sgemm_....csv]
"""
import argparse
from pathlib import Path

import pandas as pd

from results_io import RESULTS, ROOT, newest

OUT = ROOT / "src" / "kernels" / "v9_dispatch_table.inc"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--csv", type=Path)
    path = ap.parse_args().csv or newest("tune_sgemm_*.csv")
    if path is None:
        raise SystemExit("no results/tune_sgemm_*.csv")
    t = pd.read_csv(path)
    t = t[t.kernel != "cublas"]
    failed = set(t[t.status != "PASS"].kernel)
    ok = t[~t.kernel.isin(failed)]
    lines = [f"// GENERATED by scripts/gen_dispatch.py from results/{Path(path).name}.",
             "// Do not edit: rerun the script after a new tuning run.",
             "// {size, config}: best % of paired cuBLAS at that size in the tuning run."]
    for n in sorted(ok.M.unique()):
        g = ok[ok.M == n]
        b = g.loc[g.pct_cublas.idxmax()]
        lines.append(f'{{{int(n)}, "{b.kernel}"}},  // {b.pct_cublas:.1f}% in the tuning run')
    if failed:
        lines.append("// excluded (failed the cuBLAS check somewhere): " + ", ".join(sorted(failed)))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
