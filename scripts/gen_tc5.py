"""Generates src/kernels/tc5_wmma_tuned.cu from src/kernels/tc1_wmma_smem.cu (tensor-core tuning sweep).

The kernel body is tc1's, with its compile-time constants turned into template parameters and the
global->shared copies turned into general chunk loops. Mechanical, asserted replacements only, so
the MMA inner loop stays byte-for-byte tc1's.
Usage: .venv/Scripts/python scripts/gen_tc5.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "src" / "kernels" / "tc1_wmma_smem.cu").read_text(encoding="utf-8")
body = src[src.index("namespace {"):src.index("}  // namespace") + len("}  // namespace")]


def rep(a, b, count=1):
    global body
    n = body.count(a)
    assert n == count, (a, n)
    body = body.replace(a, b)


rep('''constexpr int BM = 128, BN = 128, BK = 32;
constexpr int WARPS_M = 2, WARPS_N = 4;            // warp grid
constexpr int WM = BM / WARPS_M, WN = BN / WARPS_N;  // 64 x 32 per warp
constexpr int FM = WM / 16, FN = WN / 16;            // 4 x 2 fragments per warp
constexpr int THREADS = WARPS_M * WARPS_N * 32;      // 256
constexpr int PAD = 8;                               // halves
constexpr int LDA = BK + PAD, LDB = BN + PAD;        // 40, 136
''', '''// Shape of one configuration, with the checks WMMA and the T4 impose.
template <int BM_, int BN_, int BK_, int WARPS_M_, int WARPS_N_>
struct TcCfg {
    static constexpr int BM = BM_, BN = BN_, BK = BK_, WARPS_M = WARPS_M_, WARPS_N = WARPS_N_;
    static constexpr int WM = BM / WARPS_M, WN = BN / WARPS_N;  // warp tile
    static constexpr int FM = WM / 16, FN = WN / 16;            // fragments per warp
    static constexpr int THREADS = WARPS_M * WARPS_N * 32;
    static constexpr int PAD = 8;                               // halves
    static constexpr int LDA = BK + PAD, LDB = BN + PAD;
    static constexpr int SMEM_BYTES = (BM * LDA + BK * LDB) * 2;
    static_assert(BM % WARPS_M == 0 && BN % WARPS_N == 0, "warp grid must tile the block");
    static_assert(WM % 16 == 0 && WN % 16 == 0, "warp tile must be whole 16x16 fragments");
    static_assert(BK % 16 == 0, "K tile must be whole 16-deep MMA steps");
    static_assert(LDA % 8 == 0 && LDB % 8 == 0, "WMMA ldm must be a multiple of 8 halves");
    // Fragment origins: rows step by 16 and columns by multiples of 16, so every origin offset
    // (row * LD + col) * 2 bytes is a multiple of 32 when 16 * LD * 2 is: true for any LD.
    static_assert((16 * LDA * 2) % 32 == 0 && (16 * LDB * 2) % 32 == 0 && (16 * 2) % 32 == 0,
                  "fragment pointers must be 32-byte aligned");
    static_assert((LDA * 2) % 16 == 0 && (LDB * 2) % 16 == 0, "uint4 shared stores need 16 B rows");
    static_assert(SMEM_BYTES <= 48 * 1024, "static shared memory limit is 48 KB per block");
    static_assert(THREADS <= 1024, "block size");
};
''')
rep('''__global__ void __launch_bounds__(THREADS)
tc1_wmma_smem_kernel(int M, int N, int K, const half* __restrict__ A, const half* __restrict__ B,
                     float* __restrict__ C) {
#if defined(__CUDA_ARCH__) && __CUDA_ARCH__ >= 700
''', '''template <int BM_, int BN_, int BK_, int WARPS_M_, int WARPS_N_, int MINB_>
__global__ void __launch_bounds__(TcCfg<BM_, BN_, BK_, WARPS_M_, WARPS_N_>::THREADS, MINB_)
tc5_wmma_tuned_kernel(int M, int N, int K, const half* __restrict__ A, const half* __restrict__ B,
                      float* __restrict__ C) {
#if defined(__CUDA_ARCH__) && __CUDA_ARCH__ >= 700
    using G = TcCfg<BM_, BN_, BK_, WARPS_M_, WARPS_N_>;
    constexpr int BM = G::BM, BN = G::BN, BK = G::BK, WARPS_N = G::WARPS_N;
    constexpr int WM = G::WM, WN = G::WN, FM = G::FM, FN = G::FN, THREADS = G::THREADS;
    constexpr int LDA = G::LDA, LDB = G::LDB;
''')
rep('''        // A tile: 128 rows x 32 halves = 512 chunks of 8 halves (16 bytes); 2 per thread.
#pragma unroll
        for (int p = 0; p < (BM * BK / 8) / THREADS; ++p) {
            const int c = tid + p * THREADS;
''', '''        // A tile: BM rows x BK halves, in chunks of 8 halves (16 bytes).
#pragma unroll
        for (int c = tid; c < BM * BK / 8; c += THREADS) {
''')
rep('''        // B tile: 32 rows x 128 halves = 512 chunks; 2 per thread.
#pragma unroll
        for (int p = 0; p < (BK * BN / 8) / THREADS; ++p) {
            const int c = tid + p * THREADS;
''', '''        // B tile: BK rows x BN halves, in chunks of 8 halves.
#pragma unroll
        for (int c = tid; c < BK * BN / 8; c += THREADS) {
''')
assert "tc1_" not in body, [l for l in body.splitlines() if "tc1_" in l]

header = '''// tc5_wmma_tuned.cu — tensor-core track: tc1's WMMA kernel as a template, for a tuning sweep.
// GENERATED by scripts/gen_tc5.py from tc1_wmma_smem.cu; edit the generator, not this file.
//
// WHAT CHANGED vs tc1
//   Nothing in the schedule or the MMA loop (single shared buffer, 8-half row padding, uint4
//   global->shared copies, two barriers per K tile). The block tile, K depth, warp grid and the
//   __launch_bounds__ minimum blocks per SM become template parameters, and the copies become
//   general chunk loops so any shape works. bench --tc-tune runs the configurations listed at the
//   end against cublasGemmEx, the same way bench --tc runs tc0-tc4.
//
// WHY
//   tc1 (one fixed 128x128x32 shape, 8 warps of 64x32) is the best tensor-core kernel so far, and
//   the hand-written PTX variants (tc3, tc4) showed the instruction path isn't the limit (the
//   compiler already emits LDSM + HMMA). On the FP32 side, the shape and occupancy sweep (v10) was
//   worth several points; this asks the same question for tensor cores.
//
// WHAT THE LIMIT IS NOW
//   Measured, not assumed: results/tctune_sgemm_*.csv. Sizes: multiples of the block tile only
//   (bench uses 256..4096); sm_70+.

#include "kernels.h"

#include <mma.h>

'''

footer = '''

// Name: tc5_<BM>x<BN>x<BK>_w<WARPS_M>x<WARPS_N>_b<MINB>.
template <int BM, int BN, int BK, int WM_, int WN_, int MINB>
void launch_tc5(int M, int N, int K, const half* A, const half* B, float* C) {
    dim3 grid(ceil_div(N, BN), ceil_div(M, BM));
    tc5_wmma_tuned_kernel<BM, BN, BK, WM_, WN_, MINB>
        <<<grid, TcCfg<BM, BN, BK, WM_, WN_>::THREADS>>>(M, N, K, A, B, C);
}

template <int BM, int BN, int BK, int WM_, int WN_, int MINB>
KernelResources resources_tc5() {
    return kernel_resources(tc5_wmma_tuned_kernel<BM, BN, BK, WM_, WN_, MINB>,
                            TcCfg<BM, BN, BK, WM_, WN_>::THREADS);
}

}  // namespace

#define TC5_CFG(bm, bn, bk, wm, wn, mb)                                                         \\
    TcConfig {                                                                                  \\
        "tc5_" #bm "x" #bn "x" #bk "_w" #wm "x" #wn "_b" #mb, launch_tc5<bm, bn, bk, wm, wn, mb>, \\
            resources_tc5<bm, bn, bk, wm, wn, mb>                                               \\
    }

const std::vector<TcConfig>& tc5_tune_configs() {
    static const std::vector<TcConfig> configs = {
        TC5_CFG(128, 128, 32, 2, 4, 2),   // = tc1
        TC5_CFG(128, 128, 32, 2, 2, 2),   // 4 warps of 64x64
        TC5_CFG(128, 256, 32, 2, 4, 1),   // 8 warps of 64x64
        TC5_CFG(256, 128, 32, 4, 2, 1),   // 8 warps of 64x64
        TC5_CFG(128, 128, 64, 2, 4, 1),   // deeper K tile: half the barriers
        TC5_CFG(64, 128, 32, 2, 2, 4),    // 4 warps of 32x64
        TC5_CFG(128, 64, 32, 2, 2, 4),    // 4 warps of 64x32
        TC5_CFG(64, 64, 32, 2, 2, 6),     // 4 warps of 32x32
    };
    return configs;
}
'''
# the anonymous namespace must stay open for the launch/resources templates: drop its closing line
assert body.endswith("}  // namespace")
body = body[: -len("}  // namespace")].rstrip() + "\n"
(ROOT / "src" / "kernels" / "tc5_wmma_tuned.cu").write_text(header + body + footer, encoding="utf-8", newline="\n")
print("wrote src/kernels/tc5_wmma_tuned.cu")
