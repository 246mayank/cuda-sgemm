"""Writes the generated tables into README.md between marker comments:

  <!-- BEGIN GENERATED: results -->
  ...
  <!-- END GENERATED: results -->

Nothing between the markers should be edited by hand; rerun this script instead.
Usage: .venv/Scripts/python scripts/make_tables.py [--csv results/sgemm_....csv]
"""
import re

from results_io import ROOT, kernels_in, load_run, nvsmi_row, parse_args, peak_fp32_gflops

README = ROOT / "README.md"
BEGIN, END = "<!-- BEGIN GENERATED: results -->", "<!-- END GENERATED: results -->"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def environment(env, csv_path):
    start, end = nvsmi_row(env["nvidia_smi_start"]), nvsmi_row(env["nvidia_smi_end"])
    peak = peak_fp32_gflops(env)
    cuda = lambda v: f"{v // 1000}.{(v % 1000) // 10}"
    lines = [
        f"- GPU: **{env['gpu_name']}** (sm_{env['compute_capability'].replace('.', '')}), "
        f"{env['sm_count']} SMs, max SM clock {env['sm_clock_max_khz'] // 1000} MHz",
        f"- CUDA runtime {cuda(env['cuda_runtime_version'])}, nvcc {env['nvcc_version']}, "
        f"driver {start.get('driver_version', 'n/a')}, cuBLAS {env['cublas_version']}",
        f"- Run: {env['date_utc']}; {env['warmup_runs']} warm-ups + {env['timed_runs']} timed "
        f"runs per point; source `results/{csv_path.name}`",
        f"- SM clock / temperature / power at start of run: "
        f"{start.get('clocks.current.sm [MHz]', 'n/a')} / {start.get('temperature.gpu', 'n/a')} C / "
        f"{start.get('power.draw [W]', 'n/a')} (limit {start.get('power.limit [W]', 'n/a')})",
        f"- SM clock / temperature / power at end of run: "
        f"{end.get('clocks.current.sm [MHz]', 'n/a')} / {end.get('temperature.gpu', 'n/a')} C / "
        f"{end.get('power.draw [W]', 'n/a')} (limit {end.get('power.limit [W]', 'n/a')})",
    ]
    if peak:
        lines.append(f"- Theoretical FP32 peak (SMs x 64 lanes x max clock x 2): "
                     f"{peak:,.0f} GFLOP/s")
    return "\n".join(lines)


def headline_table(df):
    size = df.M.max()
    d = df[df.M == size]
    rows = []
    for k in ["cublas"] + kernels_in(d):
        r = d[d.kernel == k].iloc[0]
        if r.status == "FAILED":
            rows.append([k, "FAILED", "", "", "", f"{r.max_rel_err:.1e}", "FAILED"])
            continue
        rows.append([
            "cuBLAS" if k == "cublas" else f"`{k}`",
            f"{r.gflops:,.0f}",
            f"{r.median_ms:.2f}",
            f"{r.min_ms:.2f} – {r.p90_ms:.2f}",
            f"{r.pct_cublas:.1f}%",
            "reference" if k == "cublas" else f"{r.max_rel_err:.1e}",
            r.status,
        ])
    header = ["kernel", "GFLOP/s", "median ms", "min – p90 ms", "% cuBLAS", "max rel err",
              "check"]
    notes = []
    if "cublas_paired_median_ms" in df.columns:
        notes.append("% cuBLAS compares each kernel with cuBLAS calls interleaved with its own "
                     "timed runs (same thermal state), so it can differ from the ratio to the "
                     "standalone cuBLAS row.")
    skipped = [k for k in kernels_in(df) if k not in set(d.kernel)]
    if skipped:
        notes.append("Not run at this size: " + ", ".join(f"`{k}`" for k in skipped)
                     + f" (largest size run: "
                     + ", ".join(str(df[df.kernel == k].M.max()) for k in skipped) + ").")
    return (f"**N = {size}** (M = N = K), GFLOP/s from the median time:\n\n"
            + md_table(header, rows) + "".join(f"\n\n{n}" for n in notes))


def all_sizes_table(df):
    sizes = sorted(df.M.unique())
    rows = []
    for k in ["cublas"] + kernels_in(df):
        cells = []
        for s in sizes:
            r = df[(df.kernel == k) & (df.M == s)]
            if r.empty:
                cells.append("")
            elif r.status.iloc[0] == "FAILED":
                cells.append("FAILED")
            else:
                cells.append(f"{r.gflops.iloc[0]:,.0f}")
        rows.append(["cuBLAS" if k == "cublas" else f"`{k}`"] + cells)
    return ("GFLOP/s at every size (1000 and 1023 test boundary handling):\n\n"
            + md_table(["kernel"] + [str(s) for s in sizes], rows))


def main():
    args = parse_args(__doc__)
    df, env, csv_path = load_run(args.csv)
    block = "\n\n".join([
        BEGIN,
        "_Generated by `scripts/make_tables.py` from the CSV below. Do not edit by hand._",
        headline_table(df),
        all_sizes_table(df),
        "Environment:\n\n" + environment(env, csv_path),
        END,
    ])
    text = README.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        text = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, text,
                      flags=re.S)
    else:
        raise SystemExit(f"README.md has no {BEGIN} / {END} markers")
    README.write_text(text, encoding="utf-8")
    print(f"updated README.md from {csv_path.name}")


if __name__ == "__main__":
    main()
